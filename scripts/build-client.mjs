// Bundle the preview iframe client (src/core/client/client.ts + vite's module
// runner) into ONE self-contained ESM string, written to
// src/core/generated/client.ts as `CLIENT_SOURCE`.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { nodeResolve } from '@rollup/plugin-node-resolve';
import { rollup } from 'rollup';
import esbuild from 'rollup-plugin-esbuild';

const input = fileURLToPath(new URL('../src/core/client/client.ts', import.meta.url));
const out = fileURLToPath(new URL('../src/core/generated/client.ts', import.meta.url));

const bundle = await rollup({
    input,
    plugins: [
        nodeResolve({ extensions: ['.ts', '.mjs', '.js'], browser: true }),
        esbuild({ target: 'es2022', tsconfig: false, minify: true }),
    ],
});

const { output } = await bundle.generate({ format: 'es', inlineDynamicImports: true });
await bundle.close();

const code = output[0].code;
const header = '// GENERATED by scripts/build-client.mjs — do not edit. Run `pnpm build:client`.\n';
await writeFile(out, `${header}export const CLIENT_SOURCE = ${JSON.stringify(code)};\n`);
console.log(`built preview client: ${(code.length / 1024).toFixed(1)} KB`);
